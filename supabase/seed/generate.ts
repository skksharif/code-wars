/**
 * Builds the seed SQL (problems, samples and hidden tests) from problems.ts.
 *
 *   npm run seed:generate
 *
 * Hidden tests are derived from HIDDEN_TEST_SALT, a secret kept in
 * apps/worker/.dev.vars (git-ignored). The output file contains the hidden
 * tests and their answers, so it is written to a git-ignored folder and must
 * never be committed. Apply it with `node scripts/db-apply.mjs`.
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { PROBLEMS, setHiddenTestSalt } from "./problems.ts";

const TAG = "$cw$";

function quote(text: string): string {
  if (text.includes(TAG)) throw new Error(`Seed text must not contain ${TAG}`);
  return `${TAG}${text}${TAG}`;
}

export function buildSeedSql(salt: string): string {
  if (salt.length < 16) throw new Error("The hidden-test salt must be at least 16 characters.");
  setHiddenTestSalt(salt);

  const out: string[] = [
    "-- GENERATED by supabase/seed/generate.ts. Do not edit by hand.",
    "-- CONFIDENTIAL: contains hidden tests and their answers. Never commit this file.",
    "",
  ];

  for (const p of PROBLEMS) {
    const hidden = p.hidden();
    // Inputs must be clean for every salt, not just the one the tests use.
    for (const input of [...p.samples.map((s) => s.input), ...hidden]) {
      if (input.length === 0 || /\n\n|\s$|^\s|\r/.test(input)) {
        throw new Error(`${p.slug}: a test input is empty or has stray whitespace`);
      }
    }
    if (hidden.length < 5) throw new Error(`${p.slug}: fewer than 5 hidden tests`);

    const samples = p.samples.map((s) => ({
      input: s.input,
      output: p.solve(s.input),
      ...(s.explanation ? { explanation: s.explanation } : {}),
    }));

    out.push(
      `insert into public.problems (slug, title, statement_md, difficulty, samples)`,
      `values (${quote(p.slug)}, ${quote(p.title)}, ${quote(p.statement)}, ${quote(p.difficulty)}, ${quote(JSON.stringify(samples))}::jsonb)`,
      `on conflict (slug) do update set`,
      `  title = excluded.title, statement_md = excluded.statement_md,`,
      `  difficulty = excluded.difficulty, samples = excluded.samples;`,
      `delete from public.problem_tests where problem_id = (select id from public.problems where slug = ${quote(p.slug)});`,
    );

    hidden.forEach((input, index) => {
      out.push(
        `insert into public.problem_tests (problem_id, ordinal, input, expected_output)`,
        `values ((select id from public.problems where slug = ${quote(p.slug)}), ${index + 1}, ${quote(input)}, ${quote(p.solve(input))});`,
      );
    });
    out.push("");
  }

  return out.join("\n");
}

export const SEED_PATH = join(import.meta.dirname, ".generated", "seed.sql");

/** Reads HIDDEN_TEST_SALT from the environment or apps/worker/.dev.vars. */
export function readSalt(): string | null {
  const fromEnv = process.env.HIDDEN_TEST_SALT?.trim();
  if (fromEnv) return fromEnv;
  const file = join(import.meta.dirname, "..", "..", "apps", "worker", ".dev.vars");
  if (!existsSync(file)) return null;
  const line = readFileSync(file, "utf8")
    .split(/\r?\n/)
    .find((l) => l.startsWith("HIDDEN_TEST_SALT="));
  return line?.slice("HIDDEN_TEST_SALT=".length).trim() || null;
}

if (process.argv[1] && process.argv[1].endsWith("generate.ts")) {
  const salt = readSalt();
  if (!salt) {
    console.error("HIDDEN_TEST_SALT is not set in apps/worker/.dev.vars.");
    process.exit(1);
  }
  mkdirSync(dirname(SEED_PATH), { recursive: true });
  writeFileSync(SEED_PATH, buildSeedSql(salt), "utf8");
  console.log(`Wrote ${SEED_PATH} (${PROBLEMS.length} problems). Do not commit it.`);
}
